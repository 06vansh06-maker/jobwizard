export function emailVariation(recruiterName: string, company: string, firstName: string, variant: number): string {
  const first = recruiterName.split(' ')[0];
  const variants = [
    `Hi ${first},\n\nI noticed ${company} is growing its engineering team and your background in hiring for ${first === 'Priya' ? 'product-minded' : 'technical'} roles stood out.\n\nI'm ${firstName}, a full-stack engineer (React, TypeScript, Python) with recent production LLM work. I just applied to a relevant role and would love 15 minutes to share why I could be a strong fit.\n\nWould early next week work for a brief intro?\n\nBest,\n${firstName}`,
    `Hi ${first},\n\nI'll keep this short: I'm a full-stack engineer with 4 years across React, TypeScript and Python, including LLM-powered products in production.\n\n${company} looks like exactly the environment where I do my best work. Could we find 15 minutes next week to discuss where I could contribute?\n\nBest,\n${firstName}`,
    `Hi ${first},\n\nYour team at ${company} caught my eye — particularly the focus on high-quality engineering hires.\n\nI'm ${firstName}, working across React and Python with recent AI feature work shipped to production. I'd value a 15-minute conversation about open roles where my background fits.\n\nOpen to a brief chat next week?\n\nThanks,\n${firstName}`,
  ];
  return variants[variant % variants.length];
}

